#range ja for
for n in range(1, 10):
    print(n)

#toinen eri range funktio (ajo ei toimi samalla kertaa, mutta nyt tulostetaan kahden välein)

for n in range(1, 11, 2):
    print(n)

#kolmas eri range funktio (ajo ei toimi samalla kertaa, mutta nyt tulostetaan aiona yksi vähemmän välein)

for n in range(5, 0, -1):
    print(n)