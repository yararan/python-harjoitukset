#alustetaan muuttujat 
tavoiteluku = 1000
numerot = 0

#luodaan toteutus while-funktiolla
while True:
    numerot +=3 

#luodaan lopettava ehto
    if numerot >= tavoiteluku:
        break
    print("Tulostettu kolmella jaolliset numerot: ", numerot)


#Tulostetaan tiedote, mitä juuri tehtiin
print("Tuhat täynnä kolmella jaollisilla luvuilla")

