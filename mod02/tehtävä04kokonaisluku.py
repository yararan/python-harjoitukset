ensimmäinen_kokonaisluku = input ("ensimmäinen kokonaisluku: ")
toinen_kokonaisluku = input ("toinen kokonaisluku: ")
kolmas_kokonaisluku = input ("kolmas kokonaisluku: ")
ensimmäinen_kokonaisluku = int(ensimmäinen_kokonaisluku)
toinen_kokonaisluku = int(toinen_kokonaisluku)
kolmas_kokonaisluku = int(kolmas_kokonaisluku)
summa = ensimmäinen_kokonaisluku + toinen_kokonaisluku + kolmas_kokonaisluku
tulo = ensimmäinen_kokonaisluku *toinen_kokonaisluku * kolmas_kokonaisluku
keskiarvo = (ensimmäinen_kokonaisluku + toinen_kokonaisluku + kolmas_kokonaisluku) / 3
print ("Summa on ",summa)
print ("Tulo on ",tulo)
print ("Keskiarvo on ",keskiarvo)
